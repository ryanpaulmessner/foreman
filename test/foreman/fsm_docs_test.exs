defmodule Foreman.FsmDocsTest do
  use ExUnit.Case, async: true

  test "diagram uses named group rows once and leaves group stays to the matrix" do
    text = Foreman.Stage.to_mermaid()
    assert text =~ "stateDiagram-v2\n    [*] --> queued\n"
    assert text =~ "working --> building: progress / append(progress), emit(stage)"
    assert text =~ ~s(state "working: dispatched, building" as working)
    refute text =~ "after_report --> after_report"
  end

  test "matrix includes guarded fallbacks and ordered entry effects" do
    text = Foreman.Stage.matrix()

    assert text =~
             "| building | dispatch [new_session?] | -> dispatched | record(session), append(redispatched), emit(stage) |"

    assert text =~ "| building | dispatch | invalid |  |"

    assert text =~
             "| pr_open | cr_merged | -> merged | record(merge), emit(stage), suggest(close_bead) |"

    assert text =~ "| abandoned | cr_merged | ignored |  |"
    assert length(String.split(String.trim(text), "\n")) == 145
  end

  for {name, module} <- [
        {"stage", Foreman.Stage},
        {"request", Foreman.Request},
        {"request_wait", Foreman.RequestWait},
        {"notification_permission", Foreman.NotificationPermission},
        {"delivery_machine", Foreman.DeliveryMachine},
        {"spool_machine", Foreman.SpoolMachine},
        {"session_machine", Foreman.SessionMachine},
        {"epic", Foreman.Epic},
        {"disclosure", Foreman.Initiatives.Disclosure},
        {"ticket_sheet", Foreman.TicketSheet},
        {"card_panel", Foreman.CardPanel},
        {"os_notification", Foreman.OsNotification},
        {"request_drawer", Foreman.RequestDrawer},
        {"waiting_card", Foreman.WaitingCard},
        {"reload_machine", Foreman.Config.ReloadMachine},
        {"read_machine", Foreman.Beads.ReadMachine},
        {"read_lifecycle", Foreman.Forge.ReadLifecycle},
        {"refresh_status", Foreman.Forge.RefreshStatus},
        {"action", Foreman.Merge.Action},
        {"schedule_machine", Foreman.Beads.ScheduleMachine},
        {"sync_machine", Foreman.Beads.SyncMachine},
        {"watch_machine", Foreman.Config.WatchMachine},
        {"reader_machine", Foreman.TicketFiles.ReaderMachine},
        {"priority_override", Foreman.PriorityOverride}
      ] do
    test "#{name} documentation matches the committed golden" do
      module = unquote(module)

      rendered =
        "# #{unquote(name)}\n\nGenerated by `mix foreman.fsm.docs`. Do not edit by hand.\n\n```mermaid\n" <>
          module.to_mermaid() <> "```\n\n" <> module.matrix()

      assert File.read!("docs/machines/#{unquote(name)}.md") == rendered
    end
  end
end
